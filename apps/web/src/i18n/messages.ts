/**
 * French typography: a narrow no-break space before ? ! ; and a no-break space before :
 * Written once here, so the French texts above can be typed with ordinary spaces.
 */
function frenchSpacing<T>(value: T): T {
  if (typeof value === "string") {
    return value.replace(/ ([?!;])/g, " $1").replace(/ :/g, " :") as T;
  }
  if (typeof value === "function") {
    return ((...args: unknown[]) =>
      frenchSpacing((value as (...a: unknown[]) => unknown)(...args))) as T;
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, inner]) => [key, frenchSpacing(inner)]),
    ) as T;
  }
  return value;
}

const MESSAGES: Record<Locale, Messages> = { en, fr: frenchSpacing(fr), ru };

export function messagesFor(locale: Locale): Messages {
  return MESSAGES[locale];
}
